# Подсчитайте количество слов-палиндромов в предложении.
# Регистр не учитывать; односимвольные слова тоже считаются палиндромами.
#
# Пример: 'Дед пошёл искать шалаш и топот' → количество `4`.

string = "Дед пошёл искать шалаш и топот"
string = string.lower()
count = 0
new_list = string.split()
for num in new_list:
    if num == num[::-1]:
        count += 1
print(count)


